from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


# =====================================================
# 1. COMMON AGENT CONTRACTS
# =====================================================

AgentStatus = Literal["completed", "partial", "failed"]


class AgentError(BaseModel):
    """Standard error information returned by an agent."""

    model_config = ConfigDict(extra="forbid")

    code: str = Field(min_length=1)
    message: str = Field(min_length=1)
    details: str | None = None


class AgentInput(BaseModel):
    """Common input structure for all agents."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(min_length=1)
    user_request: str = Field(min_length=1)
    context: dict[str, Any] = Field(default_factory=dict)


class AgentResponse(BaseModel):
    """Common output structure for all agents."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(min_length=1)
    agent_name: str = Field(min_length=1)

    status: AgentStatus

    result: dict[str, Any] = Field(default_factory=dict)

    next_agent: str | None = None

    error: AgentError | None = None


class WorkflowResponse(BaseModel):
    """Final response structure for the complete workflow."""

    model_config = ConfigDict(extra="forbid")

    workflow_id: str = Field(min_length=1)

    status: AgentStatus

    agents_executed: list[str] = Field(default_factory=list)

    final_result: dict[str, Any] = Field(default_factory=dict)


# =====================================================
# 2. ANALYSIS AGENT SCHEMAS
# =====================================================

class AnalysisInput(BaseModel):
    """Input received by the Analysis Agent."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(min_length=1)

    user_request: str = Field(min_length=1)

    research_data: Any

    context: dict[str, Any] = Field(default_factory=dict)


class AnalysisResult(BaseModel):
    """Structured output generated by the Analysis Agent."""

    model_config = ConfigDict(extra="forbid")

    key_findings: list[str]

    identified_problems: list[str]

    trends_and_patterns: list[str]

    analysis_summary: str


# =====================================================
# 3. DECISION AGENT SCHEMAS
# =====================================================

class DecisionOption(BaseModel):
    """Validated structure for a business decision option."""

    model_config = ConfigDict(extra="forbid")

    name: str = Field(min_length=1)

    cost: float = Field(ge=0)

    benefit: float = Field(ge=0)

    risk: float = Field(default=0, ge=0)

class DecisionCriteria(BaseModel):
    model_config = ConfigDict(extra="forbid")

    benefit_weight: float = Field(default=1.0, ge=0)
    cost_weight: float = Field(default=1.0, ge=0)
    risk_weight: float = Field(default=1.0, ge=0)

class DecisionInput(BaseModel):
    """Input received by the Decision Agent."""

    model_config = ConfigDict(extra="forbid")

    task_id: str = Field(min_length=1)

    analysis_result: dict[str, Any]

    # Kept as dictionaries temporarily to preserve
    # compatibility with the existing Decision Agent.
    available_options: list[dict[str, Any]]

    evaluation_criteria: dict[str, Any] = Field(default_factory=dict)

    context: dict[str, Any] = Field(default_factory=dict)


class DecisionResult(BaseModel):
    """Structured output generated by the Decision Agent."""

    model_config = ConfigDict(extra="forbid")

    evaluated_options: list[dict[str, Any]]

    risks_and_benefits: dict[str, Any]

    recommended_decision: str

    reasoning: str
